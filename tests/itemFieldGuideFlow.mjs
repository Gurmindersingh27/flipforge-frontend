import assert from 'node:assert/strict';

export async function runFieldGuideChecks({ cdp, evaluate, until, fill, click, measure, screenshot, checks }) {
  const input = id => `document.getElementById(${JSON.stringify(id)})`;
  const choose = async (id, value) => {
    await evaluate(`(()=>{const el=${input(id)};Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  };
  const before = await (await fetch('http://127.0.0.1:8000/browser-fixture/ai')).json();
  for (const width of [390,1440]) {
    await cdp('Emulation.setDeviceMetricsOverride', {width,height:width===390?844:1000,deviceScaleFactor:1,mobile:width===390});
    await cdp('Page.navigate', {url:'http://127.0.0.1:5173/items?fixtureSignedOut=1'});
    await until(`Boolean(document.querySelector('[data-field-guide]'))`);
    assert.equal(await evaluate(`document.querySelector('[data-field-guide]').open`), false);
    assert.equal(await evaluate(`document.querySelector('.field-guide-form button').disabled`), true);
    await evaluate(`window.guideRequests=[];const original=window.fetch;window.fetch=(...args)=>{window.guideRequests.push(String(args[0]));return original(...args);};document.querySelector('[data-field-guide]>summary').click()`);
    assert.equal(await evaluate(`document.querySelectorAll('.field-guide-check input[value=unchecked]:checked').length`),5);
    await choose('field-guide-kind','chair'); await choose('field-guide-brand','herman-miller');
    assert.equal(await evaluate(`document.querySelector('.field-guide-label a').hostname`),'www.hermanmiller.com');
    assert.ok(await evaluate(`document.querySelector('.field-guide-label').textContent.includes('FO number')`));
    await fill(input('quick-description'),'Seller says Mirra. ');
    await fill(input('field-guide-label-text'),'Herman Miller MR??');
    await evaluate(`document.querySelector('input[name="chair-height"][value=issue]').click();document.querySelector('input[name="chair-frame"][value=okay]').click()`);
    await until(`document.querySelector('.field-guide-progress').textContent.includes('3 of 5')`);
    await fill(input('field-guide-notes'),'Height drops; date unreadable.');
    const preview = await evaluate(`document.querySelector('.field-guide-preview p').textContent`);
    assert.match(preview,/Model\/version not verified/);
    assert.match(preview,/Issue found: seat height/);
    assert.match(preview,/Not checked: tilt and controls/);
    await click('button','Add notes to description');
    assert.equal(await evaluate(input('quick-description')+'.value'),'Seller says Mirra. \n\n'+preview);
    assert.equal(await evaluate(input('quick-asking')+'.value'),'');
    assert.equal(await evaluate(`document.querySelector('.field-guide-form button').disabled`),true);
    assert.deepEqual(await evaluate('window.guideRequests'),[]);
    assert.ok(await measure('document.documentElement.scrollWidth<=innerWidth'));
    assert.ok(await evaluate(`Array.from(document.querySelectorAll('.field-guide-answers label')).every(el=>el.getBoundingClientRect().height>=44)`));
    await evaluate(`document.querySelector('[data-field-guide]').scrollIntoView({block:'start'})`);
    await screenshot(`photo-field-guide-label-${width}.png`);
    await evaluate(`document.querySelector('.field-guide-progress').scrollIntoView({block:'start'})`);
    await screenshot(`photo-field-guide-checks-${width}.png`);
    await evaluate(`document.querySelector('input[name="chair-frame"][value=issue]').click()`);
    assert.equal(await evaluate(`document.querySelector('.field-guide-form button').disabled`),true);
    assert.equal(await evaluate(input('quick-description')+'.value'),'Seller says Mirra. \n\n'+preview);
    assert.ok(await evaluate(`document.querySelector('[data-field-guide]').textContent.includes('Your guide has changed')`));
    await choose('field-guide-brand','steelcase');
    assert.equal(await evaluate(`document.querySelector('.field-guide-label a').hostname`),'sg.steelcase.com');
    await choose('field-guide-kind','storage');
    assert.equal(await evaluate(`document.querySelectorAll('.field-guide-check input[value=unchecked]:checked').length`),5);
    assert.ok(!await evaluate(`document.querySelector('.field-guide-preview p').textContent.includes('Issue found: seat height')`));
    await fill(input('quick-description'),'x'.repeat(500));
    await until(`document.querySelector('.field-guide-form .quick-error')?.textContent.includes('over its 500-character limit')`);
    assert.equal(await evaluate(`document.querySelector('.field-guide-form button').disabled`),true);
    assert.equal(await evaluate(input('quick-description')+'.value'),'x'.repeat(500));
    await fill(input('field-guide-label-text'),'<img src=x onerror=alert(1)>');
    assert.equal(await evaluate(`document.querySelector('.field-guide-preview img')`),null);
    assert.ok(await evaluate(`document.querySelector('.field-guide-preview').textContent.includes('<img src=x')`));
    assert.deepEqual(await evaluate('window.guideRequests'),[]);
    await cdp('Page.reload'); await until(`Boolean(document.querySelector('[data-field-guide]'))`);
    assert.equal(await evaluate(input('field-guide-label-text')+'.value'),'');
    assert.equal(await evaluate(input('field-guide-notes')+'.value'),'');
    assert.equal(await evaluate(input('quick-description')+'.value'),'');
  }
  checks.push('Free collapsed field guide works signed out at phone and desktop widths without API requests');
  checks.push('Partial labels remain unverified; chair answers retain untested checks and append without changing the asking price');
  checks.push('Description overflow and conflicting repeat additions are blocked without replacing text; label text cannot inject HTML');
  checks.push('Checklist changes do not reuse other-category answers; page-local inspection drafts clear on reload');
  await cdp('Page.navigate',{url:'http://127.0.0.1:5173/items'});
  await until(`Boolean(document.querySelector('[data-field-guide]'))`);
  await evaluate(`document.querySelector('[data-field-guide]>summary').click()`);
  await fill(input('field-guide-notes'),'Private observation from first account');
  await evaluate(`window.switchFixtureUser('other-user')`);
  await until(`${input('field-guide-notes')}?.value===''`);
  assert.equal(await evaluate(`document.querySelector('[data-field-guide]').open`),false);
  await evaluate(`document.querySelector('[data-field-guide]>summary').click()`);
  await fill(input('field-guide-notes'),'Private observation from second account');
  await evaluate(`window.switchFixtureSession('replacement-session')`);
  await until(`${input('field-guide-notes')}?.value===''`);
  assert.equal(await evaluate(`document.querySelector('[data-field-guide]').open`),false);
  const after = await (await fetch('http://127.0.0.1:8000/browser-fixture/ai')).json();
  assert.equal(after.calls,before.calls);
  assert.equal(after.posts,before.posts);
  checks.push('Account/session changes clear private inspection drafts; all guide actions send zero assessment/provider calls');
}
